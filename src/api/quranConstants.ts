export function buildSurahObject(id: number, nameAr: string, nameEn: string): Surah {
  const trName = SURAH_TURKISH_NAMES[id] || nameEn;
  const verseCount = SURAH_VERSE_COUNTS[id] || 7;
  const pageNumber = SURAH_PAGE_NUMBERS[id] || 1;
  const slug = trName
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '-')
    .replace(/-+/g, '-');

  return {
    id,
    name: trName,
    name_en: nameEn,
    name_original: nameAr,
    slug,
    verse_count: verseCount,
    page_number: pageNumber,
    audio: {
      mp3: `https://cdn.islamic.network/quran/audio-surah/128/ar.alafasy/${id}.mp3`,
      duration: 0,
      mp3_en: '',
      duration_en: 0,
    },
  };
}

